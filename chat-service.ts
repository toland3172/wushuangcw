// 创建HTTP服务器
const server = createServer(async (req, res) => {
  // 设置CORS头
  res.setHeader('Access-Control-Allow-Origin', '*');
  res.setHeader('Access-Control-Allow-Methods', 'POST, OPTIONS');
  res.setHeader('Access-Control-Allow-Headers', 'Content-Type');
  
  if (req.method === 'OPTIONS') {
    res.writeHead(200);
    res.end();
    return;
  }
  
  const parsedUrl = parse(req.url || '', true);
  
  if (req.method === 'POST' && parsedUrl.pathname === '/chat') {
    let body = '';
    
    req.on('data', chunk => {
      body += chunk.toString();
    });
    
    req.on('end', async () => {
      try {
        const { messages } = JSON.parse(body);
        
        // 构建完整消息列表
        const fullMessages = [
          { role: 'system' as const, content: SYSTEM_PROMPT },
          ...messages
        ];
        
        // 初始化LLM客户端
        const config = new Config();
        const client = new LLMClient(config);
        
        // 设置流式响应头
        res.writeHead(200, {
          'Content-Type': 'text/plain; charset=utf-8',
          'Transfer-Encoding': 'chunked',
          'Cache-Control': 'no-cache',
          'Connection': 'keep-alive',
        });
        
        // 流式输出
        const stream = client.stream(fullMessages, {
          model: 'doubao-seed-2-0-lite-260215',
          temperature: 0.7
        });
        
        for await (const chunk of stream) {
          if (chunk.content) {
            res.write(chunk.content.toString());
          }
        }
        
        res.end();
      } catch (error) {
        console.error('Chat error:', error);
        res.writeHead(500, { 'Content-Type': 'application/json' });
        res.end(JSON.stringify({ error: '服务暂时不可用，请稍后再试' }));
      }
    });
  } else {
    res.writeHead(404, { 'Content-Type': 'application/json' });
    res.end(JSON.stringify({ error: 'Not found' }));
  }
});

server.listen(PORT, () => {
  console.log(`AI Chat service running on http://localhost:${PORT}`);
});

export default server;
